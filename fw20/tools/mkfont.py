#!/usr/bin/env python3
"""Generate a small LVGL 9 bitmap font (lv_font_fmt_txt, 4 bpp) from a TTF.

Like lv_font_conv, but needs only Pillow (no node). Only the given characters
are included; line height is fitted tightly to those glyphs, so a digits-only
font is not padded for accents/descenders it never draws.

  python3 tools/mkfont.py --size 128 --chars ' -.0123456789' --tabular \\
      --name font_weight_128 --out main/fonts/font_weight_128.c

--tabular gives all digits the same advance (no jitter while the value changes).
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
TTF = HERE / '../managed_components/lvgl__lvgl/scripts/built_in_font/Montserrat-Medium.ttf'


def render(font, ch):
    """(4-bit pixel rows, box_w, box_h, ofs_x, ofs_y) relative to the baseline."""
    x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0 or ch == ' ':
        return [], 0, 0, 0, 0
    im = Image.new('L', (w, h), 0)
    ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
    px = [v >> 4 for v in im.getdata()]
    return px, w, h, x0, -y1


def pack4(px):
    """Pack 4-bit pixels continuously (lv_font_conv bitmap_format 0)."""
    if len(px) % 2:
        px = px + [0]
    return bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ttf', type=Path, default=TTF)
    ap.add_argument('--size', type=int, required=True)
    ap.add_argument('--chars', required=True)
    ap.add_argument('--name', required=True)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--tabular', action='store_true', help='equal advance for 0-9')
    a = ap.parse_args()

    font = ImageFont.truetype(str(a.ttf), a.size)
    chars = sorted(set(a.chars), key=ord)
    digit_adv = max(font.getlength(c) for c in '0123456789')

    glyphs, bitmap = [], bytearray()
    top = bottom = 0
    for ch in chars:
        px, w, h, ox, oy = render(font, ch)
        adv = font.getlength(ch)
        if a.tabular and ch.isdigit():
            ox += round((digit_adv - adv) / 2)     # centre in the wider cell
            adv = digit_adv
        glyphs.append(dict(ch=ch, idx=len(bitmap), adv=round(adv * 16),
                           w=w, h=h, ox=ox, oy=oy))
        bitmap += pack4(px)
        if h:
            top = max(top, oy + h)
            bottom = min(bottom, oy)

    margin = max(1, a.size // 32)
    base_line = -bottom + margin
    line_height = top + base_line + margin

    first = ord(chars[0])
    out = []
    w = out.append
    w('/* Generated by tools/mkfont.py from %s, size %d px, 4 bpp. Do not edit. */'
      % (a.ttf.name, a.size))
    w('/* Characters: "%s" */' % ''.join(chars).replace('\\', '\\\\').replace('*/', '*\\/'))
    w('#include "lvgl.h"\n')
    w('static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {')
    for i in range(0, len(bitmap), 16):
        w('    ' + ', '.join('0x%02x' % b for b in bitmap[i:i + 16]) + ',')
    w('};\n')
    w('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
    w('    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}, /* id 0 reserved */')
    for g in glyphs:
        w('    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* %r */'
          % (g['idx'], g['adv'], g['w'], g['h'], g['ox'], g['oy'], g['ch']))
    w('};\n')
    w('static const uint16_t unicode_list[] = {')
    w('    ' + ', '.join('0x%x' % (ord(c) - first) for c in chars) + ',')
    w('};\n')
    w('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
    w('    {')
    w('        .range_start = %d, .range_length = %d, .glyph_id_start = 1,'
      % (first, ord(chars[-1]) - first + 1))
    w('        .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = %d,'
      % len(chars))
    w('        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY')
    w('    }')
    w('};\n')
    w('static const lv_font_fmt_txt_dsc_t font_dsc = {')
    w('    .glyph_bitmap = glyph_bitmap,')
    w('    .glyph_dsc = glyph_dsc,')
    w('    .cmaps = cmaps,')
    w('    .kern_dsc = NULL,')
    w('    .kern_scale = 0,')
    w('    .cmap_num = 1,')
    w('    .bpp = 4,')
    w('    .kern_classes = 0,')
    w('    .bitmap_format = 0,')
    w('};\n')
    w('const lv_font_t %s = {' % a.name)
    w('    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,')
    w('    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,')
    w('    .line_height = %d,' % line_height)
    w('    .base_line = %d,' % base_line)
    w('    .subpx = LV_FONT_SUBPX_NONE,')
    w('    .underline_position = %d,' % -max(1, a.size // 12))
    w('    .underline_thickness = %d,' % max(1, a.size // 24))
    w('    .dsc = &font_dsc,')
    w('};')

    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text('\n'.join(out) + '\n')
    print('%s: %d glyphs, %d bytes bitmap, line_height %d, base_line %d -> %s'
          % (a.name, len(chars), len(bitmap), line_height, base_line, a.out))


if __name__ == '__main__':
    main()
